"""Build a cooperative startup wrapper; keep the original painting code intact."""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "assets" / "journey-v3"

def replace_once(text, old, new):
    assert text.count(old) == 1, f"Expected exactly one source marker: {old[:60]}"
    return text.replace(old, new, 1)

assets = (ROOT / "assets.js").read_text(encoding="utf-8")
assets = replace_once(assets, "for (let k = 0; k < 12; k++)\n", "for (let k = 0; k < 12; k++) {\n  await yieldToPage();\n")
assets = replace_once(assets, "const texture = make", "}\nawait yieldToPage();\nconst texture = make")
assets = replace_once(assets, 'const texture = make(800, 500, (c) => {', 'const texture = await makeAsync(800, 500, async (c) => {')
assets = replace_once(assets, 'const terrainPaint = make(1200, 600, (c) => {', 'const terrainPaint = await makeAsync(1200, 600, async (c) => {')
for count, batch in [(36000, 1024), (22000, 256), (1800, 256)]:
    marker = f'  for (let i = 0; i < {count}; i++) {{'
    assets = replace_once(assets, marker, marker + f'\n    if (i % {batch} === 0) await yieldToPage();')
materials = (ROOT / "materials.js").read_text(encoding="utf-8")
materials = replace_once(materials, "const M = (() => {", "const M = await (async () => {")
materials = replace_once(
    materials,
    "  const trees = Array.from({ length: 8 }, (_, k) => Array.from({ length: 4 }, (_, s) => [treeAsset(k, s, 0), treeAsset(k, s, 1)]));",
    """  const trees = [];
  for (let k = 0; k < 8; k++) {
    trees[k] = [];
    for (let s = 0; s < 4; s++) {
      trees[k][s] = [];
      for (let night = 0; night < 2; night++) {
        await yieldToPage();
        trees[k][s][night] = treeAsset(k, s, night);
      }
    }
  }""",
)
journey = (ROOT / "journey.js").read_text(encoding="utf-8")
# ResizeObserver and the startup path need not paint identical frames twice.
journey = replace_once(journey, '  width = b.width;\n  height = b.height;', '  if (width === b.width && height === b.height) return;\n  width = b.width;\n  height = b.height;')
journey = replace_once(journey, 'resize();\nrender();', 'resize();')
parts = [assets, (ROOT / "world.js").read_text(encoding="utf-8"), materials,
         (ROOT / "painting.js").read_text(encoding="utf-8"), journey]
runtime = """// Generated by scripts/build_journey_runtime.py. Do not edit this bundle by hand.
(async () => {
  const yieldToPage = () => new Promise(resolve => setTimeout(resolve, 0));
  async function makeAsync(width, height, paint) {
    const sprite = document.createElement('canvas');
    sprite.width = width;
    sprite.height = height;
    await paint(sprite.getContext('2d'));
    return sprite;
  }
  await yieldToPage();
""" + "\nawait yieldToPage();\n".join(parts) + "\n})().catch(error => { console.error(error); document.documentElement.classList.remove('journey-loading'); });\n"
(ROOT / "runtime.js").write_text(runtime, encoding="utf-8")
print("Generated cooperative journey runtime.")
